#!/bin/zsh
# Regenerate src/<grammar>/parser.rs from the released upstream crates with c2rs.
#   usage: tools/regen.sh [path to c2rs binary]
# Needs the crates unpacked in the cargo registry (any project depending on them will have fetched
# them) and the tree-sitter CLI (0.26.x).
#
# Every grammar except python is regenerated at ABI 15 from the released grammar: the shipped
# parser.c files come from different generator versions (ABI 14, or an older ABI 15 layout) that
# c2rs does not read. Python's shipped parser.c is already in the current layout and is used as is.
set -e
C2RS=${1:-c2rs}
HERE=$(cd "$(dirname "$0")/.." && pwd)
REG=$(ls -d ~/.cargo/registry/src/*/ | head -1)
W=$(mktemp -d)

emit() {  # name  dir-with-src/parser.c
  rm -f "$HERE/src/$1/parser.rs"
  $C2RS "$2/src/parser.c" "$HERE/src/$1" --export-name "tree_sitter_$1"
  rm -f "$HERE/src/$1/abi.rs"
  sed -i '' 's#^//! Generated by c2rs from .*#//! Generated by c2rs. Do not edit.#' "$HERE/src/$1/parser.rs"
  rustfmt --edition 2024 "$HERE/src/$1/parser.rs"
  test -s "$HERE/src/$1/parser.rs"
}

regen() {  # name  crate-dir  [subdir]   (subdir holds src/grammar.json)
  local dir="$W/$1"
  cp -R "$2" "$dir"
  local sub="$dir/${3:-.}"
  # ABI 15 needs a tree-sitter.json (the published typescript crate omits it); the crate version
  # ends up in the language's metadata fields.
  if [ ! -f "$sub/tree-sitter.json" ] && [ ! -f "$dir/tree-sitter.json" ]; then
    printf '{"grammars":[{"name":"%s","scope":"source.%s","path":"."}],"metadata":{"version":"%s"}}\n' "$1" "$1" "${2##*-}" > "$dir/tree-sitter.json"
  fi
  # src/grammar.json is the resolved grammar: no node dependencies needed.
  (cd "$sub" && tree-sitter generate --abi 15 src/grammar.json)
  grep -q "define LANGUAGE_VERSION 15" "$sub/src/parser.c" || { echo "$1: generator did not produce ABI 15" >&2; exit 1; }
  emit "$1" "$sub"
}

regen javascript "$REG/tree-sitter-javascript-0.25.0"
regen rust       "$REG/tree-sitter-rust-0.24.2"
regen go         "$REG/tree-sitter-go-0.25.0"
regen c          "$REG/tree-sitter-c-0.24.2"
regen java       "$REG/tree-sitter-java-0.23.5"
regen typescript "$REG/tree-sitter-typescript-0.23.2" typescript
regen tsx        "$REG/tree-sitter-typescript-0.23.2" tsx
emit python      "$REG/tree-sitter-python-0.25.0"
echo "regenerated; scanners in src/*/scanner.rs are hand-ported and untouched"
